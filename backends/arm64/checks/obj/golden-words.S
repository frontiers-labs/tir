# RUN: tir mc --march=arm64 --filetype=obj-ascii %s | filecheck %s

# Encoder golden words, byte-for-byte against clang/llvm-mc for aarch64.
# Branch immediates hold word offsets (the pc-relative byte delta >> 2), so
# `4` reads as +16 bytes. The unsigned-offset x-width ldr/str forms are not
# reachable from assembly (see limits/asm-load-offset.S); their encodings are
# pinned by the decoder round-trip unit test.

.global f
f:
    add x0, x1, x2
    lslv x0, x1, x2
    rorv x0, x1, x2
    cmp x1, x2
    cmn x1, x2
    tst x1, x2
    cmp x1, 5
    cmn x1, 5
    bic x0, x1, x2
    orn x0, x1, x2
    eon x0, x1, x2
    sdiv x0, x1, x2
    udiv x0, x1, x2
    sdiv w0, w1, w2
    udiv w0, w1, w2
    madd x0, x1, x2, x3
    msub x0, x1, x2, x3
    msub w0, w1, w2, w3
    mul x0, x1, x2
    mneg x0, x1, x2
    smulh x0, x1, x2
    lsr x0, x1, 4
    asr x0, x1, 4
    sxtb x0, w1
    sxth x0, w1
    sxtw x0, w1
    movz x0, 42
    movn x0, 42
    movk x0, 42
    adr x0, 16
    adrp x1, 5
    cset x0, eq
    csel x0, x1, x2, eq
    b.gt 4
    cbz x1, 4
    cbnz x1, 4
    tbz x1, 3, 4
    tbz x1, 35, 4
    tbnz x1, 3, 4
    ldur x0, [x1, -8]
    stur x2, [x3, -8]
    ldursw x0, [x1, -4]
    ldp x0, x1, [x2, 16]
    stp x0, x1, [x2, 16]
    ret x30

